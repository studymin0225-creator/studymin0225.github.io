# 6254. 파이썬 프로그래밍 기초 파이썬의 기본 응용
# 자료구조 - 셋, 딕셔너리 2
dic = {'홍길동': '010-1111-1111', '이순신':'010-1111-2222', '강감찬':'010-1111-3333'}

print("아래 학생들의 전화번호를 조회할 수 있습니다.")
for k in dic.keys():
    print(k)
print("전화번호를 조회하고자 하는 학생의 이름을 입력하십시오.")
student = input()
if student in dic:
    print(f'{student}의 전화번호는 {dic[student]}입니다.')
